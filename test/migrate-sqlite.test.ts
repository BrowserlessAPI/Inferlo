// Migration files on SQLite: planMigration(models, snapshot, { dialect: "sqlite" }) generates new tables, columns
// and indexes, drops and renames, applyMigrations() runs each file in one transaction, and inferlo db migrate does
// both for an app on sqlite(). Runs on the runtime's built-in SQLite: Node.js, Bun and Deno.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { after, describe, test } from "node:test";
import { applyMigrations, createDb, InferloError, model, planMigration, t } from "../src/index.ts";
import { sqlite } from "../src/db/sqlite.ts";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const isCode = (code: string) => (e: unknown) => e instanceof InferloError && e.code === code;
const file = (statements: string[]) => `-- Generated by inferlo db migrate.\n\n${statements.join(";\n\n")};\n`;
const dirs: string[] = [];
type AnyDb = { $sync(options: { dryRun: boolean }): Promise<string[]>; $sql(text: string): Promise<Record<string, unknown>[]> };
/** db push always repeats its CREATE INDEX IF NOT EXISTS statements on SQLite: compare the tables, columns and index names. */
async function matchesModels(db: AnyDb, snapshot: { tables: Record<string, { indexes: Record<string, string> }> }) {
  const pending = (await db.$sync({ dryRun: true })).filter((s) => !/^CREATE (UNIQUE )?INDEX IF NOT EXISTS/.test(s));
  assert.deepEqual(pending, [], "db push would add tables or columns");
  const indexes = (await db.$sql(`SELECT name FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL AND name NOT LIKE 'inferlo_%' ORDER BY name`)).map((r) => String(r.name));
  assert.deepEqual(indexes, Object.values(snapshot.tables).flatMap((t) => Object.keys(t.indexes)).sort());
}
after(() => {
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});
const tempDir = () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "inferlo-migrate-sqlite-"));
  dirs.push(dir);
  return dir;
};

const Team = model("ms_teams", { name: t.string().max(40).unique() });
const Note = model("ms_notes", { title: t.string().max(100), body: t.text().default(""), teamId: t.ref("ms_teams", { onDelete: "cascade" }) });
const NoteV2 = model("ms_notes", {
  title: t.string().max(100),
  body: t.text().default(""),
  teamId: t.ref("ms_teams", { onDelete: "cascade" }),
  status: t.enum(["open", "done"]).default("open"),
  slug: t.string().max(80).optional().index(),
  ownerId: t.ref("ms_teams").optional(),
  tags: t.array(t.string()).default([]),
});

describe("planMigration on SQLite", () => {
  test("the first migration creates the tables, referenced tables first, with their indexes", () => {
    const plan = planMigration([Note, Team], undefined, { dialect: "sqlite" });
    assert.match(plan.statements[0]!, /^CREATE TABLE IF NOT EXISTS "ms_teams"/);
    assert.ok(plan.statements.includes('CREATE UNIQUE INDEX IF NOT EXISTS "ms_teams_name_key" ON "ms_teams" ("name")'));
    const notes = plan.statements.find((s) => s.startsWith('CREATE TABLE IF NOT EXISTS "ms_notes"'))!;
    assert.ok(notes.includes('"team_id" TEXT NOT NULL REFERENCES "ms_teams"("id") ON DELETE CASCADE'));
    assert.ok(plan.statements.includes('CREATE INDEX IF NOT EXISTS "ms_notes_team_id_idx" ON "ms_notes" ("team_id")'));
    assert.equal(plan.snapshot.dialect, "sqlite");
    assert.deepEqual(plan.snapshot.tables.ms_notes!.columns.body, { type: "TEXT", notNull: true, default: "''" });
    assert.deepEqual(planMigration([Note, Team], plan.snapshot, { dialect: "sqlite" }).statements, [], "nothing changed");
  });

  test("new columns and indexes on an existing table; a new required column needs a default (IL4014)", () => {
    const first = planMigration([Team, Note], undefined, { dialect: "sqlite" });
    const plan = planMigration([Team, NoteV2], first.snapshot, { dialect: "sqlite" });
    assert.deepEqual(plan.statements, [
      `ALTER TABLE "ms_notes" ADD COLUMN "status" TEXT DEFAULT 'open' NOT NULL CHECK ("status" IN ('open', 'done'))`,
      'ALTER TABLE "ms_notes" ADD COLUMN "slug" TEXT',
      'ALTER TABLE "ms_notes" ADD COLUMN "owner_id" TEXT REFERENCES "ms_teams"("id") ON DELETE RESTRICT',
      `ALTER TABLE "ms_notes" ADD COLUMN "tags" TEXT DEFAULT '[]' NOT NULL`,
      'CREATE INDEX IF NOT EXISTS "ms_notes_slug_idx" ON "ms_notes" ("slug")',
      'CREATE INDEX IF NOT EXISTS "ms_notes_owner_id_idx" ON "ms_notes" ("owner_id")',
    ]);
    const required = model("ms_notes", { ...Note.fields, rank: t.int() });
    assert.throws(() => planMigration([Team, required], first.snapshot, { dialect: "sqlite" }), isCode("IL4014"));
  });

  test("drops need allowDrop (IL4017): indexes before their columns, referencing tables first", () => {
    const full = planMigration([Team, NoteV2], undefined, { dialect: "sqlite" });
    const { slug: _slug, ownerId: _owner, ...rest } = NoteV2.fields;
    const Smaller = model("ms_notes", rest);
    assert.throws(() => planMigration([Team, Smaller], full.snapshot, { dialect: "sqlite" }), (e: unknown) => isCode("IL4017")(e) && /drop column ms_notes\.slug/.test((e as Error).message));
    const plan = planMigration([Team, Smaller], full.snapshot, { dialect: "sqlite", allowDrop: true });
    assert.deepEqual(plan.statements, [
      'DROP INDEX IF EXISTS "ms_notes_slug_idx"',
      'DROP INDEX IF EXISTS "ms_notes_owner_id_idx"',
      'ALTER TABLE "ms_notes" DROP COLUMN "slug"',
      'ALTER TABLE "ms_notes" DROP COLUMN "owner_id"',
    ]);
    assert.deepEqual(planMigration([], full.snapshot, { dialect: "sqlite", allowDrop: true }).statements, ['DROP TABLE IF EXISTS "ms_notes"', 'DROP TABLE IF EXISTS "ms_teams"']);
  });

  test("renames: RENAME TO and RENAME COLUMN, indexes created again under their new names; the IL4017 fix names --rename", () => {
    const first = planMigration([Team, NoteV2], undefined, { dialect: "sqlite" });
    const { slug, title, ...rest } = NoteV2.fields;
    const Memo = model("ms_memos", { ...rest, headline: title, handle: slug });
    assert.throws(() => planMigration([Team, Memo], first.snapshot, { dialect: "sqlite" }), (e: unknown) => isCode("IL4017")(e) && /--rename ms_notes=ms_memos/.test((e as InferloError).fix!));
    const plan = planMigration([Team, Memo], first.snapshot, { dialect: "sqlite", renames: { ms_notes: "ms_memos", "ms_notes.title": "ms_memos.headline", "ms_notes.slug": "ms_memos.handle" } });
    assert.deepEqual(plan.statements, [
      'ALTER TABLE "ms_notes" RENAME TO "ms_memos"',
      'ALTER TABLE "ms_memos" RENAME COLUMN "title" TO "headline"',
      'ALTER TABLE "ms_memos" RENAME COLUMN "slug" TO "handle"',
      'DROP INDEX "ms_notes_team_id_idx"',
      'CREATE INDEX IF NOT EXISTS "ms_memos_team_id_idx" ON "ms_memos" ("team_id")',
      'DROP INDEX "ms_notes_owner_id_idx"',
      'CREATE INDEX IF NOT EXISTS "ms_memos_owner_id_idx" ON "ms_memos" ("owner_id")',
      'DROP INDEX "ms_notes_slug_idx"',
      'CREATE INDEX IF NOT EXISTS "ms_memos_handle_idx" ON "ms_memos" ("handle")',
    ]);
    assert.deepEqual(plan.renames, ["rename table ms_notes -> ms_memos", "rename column ms_notes.title -> ms_memos.headline", "rename column ms_notes.slug -> ms_memos.handle"]);
    assert.deepEqual(planMigration([Team, Memo], plan.snapshot, { dialect: "sqlite" }).statements, []);
  });

  test("column changes need allowChange (IL4019) and rebuild the table; other type changes are IL4013", () => {
    const first = planMigration([Team, NoteV2], undefined, { dialect: "sqlite" });
    const { tags: _tags, ...kept } = NoteV2.fields;
    const Changed = model("ms_notes", { ...kept, status: t.enum(["open", "done", "archived"]).default("open"), slug: t.string().max(80).default("none").index(), rank: t.number().default(0) });
    assert.throws(() => planMigration([Team, Changed], first.snapshot, { dialect: "sqlite", allowDrop: true }), (e: unknown) => isCode("IL4019")(e) && /change column ms_notes\.status \(enum values/.test((e as Error).message));
    const plan = planMigration([Team, Changed], first.snapshot, { dialect: "sqlite", allowDrop: true, allowChange: true });
    assert.match(plan.statements[0]!, /^CREATE TABLE "inferlo_new_ms_notes" \(/);
    assert.ok(plan.statements[0]!.includes(`"status" TEXT DEFAULT 'open' NOT NULL CHECK ("status" IN ('open', 'done', 'archived'))`));
    assert.deepEqual(plan.statements.slice(1), [
      `INSERT INTO "inferlo_new_ms_notes" ("id", "created_at", "updated_at", "title", "body", "team_id", "status", "slug", "owner_id") SELECT "id", "created_at", "updated_at", "title", "body", "team_id", "status", COALESCE("slug", 'none'), "owner_id" FROM "ms_notes"`,
      'DROP TABLE "ms_notes"',
      'ALTER TABLE "inferlo_new_ms_notes" RENAME TO "ms_notes"',
      'CREATE INDEX IF NOT EXISTS "ms_notes_team_id_idx" ON "ms_notes" ("team_id")',
      'CREATE INDEX IF NOT EXISTS "ms_notes_slug_idx" ON "ms_notes" ("slug")',
      'CREATE INDEX IF NOT EXISTS "ms_notes_owner_id_idx" ON "ms_notes" ("owner_id")',
    ]);
    assert.deepEqual(plan.drops, ["drop column ms_notes.tags"]);
    assert.equal(plan.changes.length, 2);
    assert.deepEqual(planMigration([Team, Changed], plan.snapshot, { dialect: "sqlite" }).statements, []);
    const counted = model("ms_counts", { n: t.int().optional(), label: t.string() });
    const countedFirst = planMigration([counted], undefined, { dialect: "sqlite" });
    const widened = planMigration([model("ms_counts", { n: t.number().optional(), label: t.string() })], countedFirst.snapshot, { dialect: "sqlite", allowChange: true });
    assert.ok(widened.statements[1]!.includes(`CAST("n" AS REAL)`));
    assert.throws(
      () => planMigration([model("ms_counts", { n: t.int().optional(), label: t.int().default(0) })], countedFirst.snapshot, { dialect: "sqlite", allowChange: true }),
      (e: unknown) => isCode("IL4013")(e) && /change column ms_counts\.label \(type TEXT -> INTEGER/.test((e as Error).message) && /integer to number/.test((e as InferloError).fix!),
    );
  });

  test("snapshots of other databases are IL4037", () => {
    const first = planMigration([Team, Note], undefined, { dialect: "sqlite" });
    assert.throws(() => planMigration([Team], planMigration([Team]).snapshot, { dialect: "sqlite" }), (e: unknown) => isCode("IL4037")(e) && /PostgreSQL/.test((e as Error).message));
    assert.throws(() => planMigration([Team], planMigration([Team], undefined, { dialect: "mysql" }).snapshot, { dialect: "sqlite" }), (e: unknown) => isCode("IL4037")(e) && /MySQL/.test((e as Error).message));
    assert.throws(() => planMigration([Team], first.snapshot), (e: unknown) => isCode("IL4037")(e) && /SQLite/.test((e as Error).message));
    assert.throws(() => planMigration([Team], first.snapshot, { dialect: "mysql" }), (e: unknown) => isCode("IL4037")(e) && /SQLite/.test((e as Error).message));
  });
});

describe("applyMigrations on SQLite", () => {
  test("generated files apply in order and are recorded once; drops and renames keep the tables in step with the models", async () => {
    const dbFile = path.join(tempDir(), "app.db");
    const db = createDb([], sqlite({ path: dbFile }));
    try {
      const first = planMigration([Team, Note], undefined, { dialect: "sqlite" });
      const second = planMigration([Team, NoteV2], first.snapshot, { dialect: "sqlite" });
      const migrations = [
        { name: "0001_init", sql: file(first.statements) },
        { name: "0002_more", sql: file(second.statements) },
      ];
      assert.deepEqual(await applyMigrations(db, migrations), ["0001_init", "0002_more"]);
      assert.deepEqual(await applyMigrations(db, migrations), []);
      const typed = createDb([Team, NoteV2], db.$adapter);
      const team = await typed.ms_teams.insert({ name: "Core" });
      const note = await typed.ms_notes.insert({ title: "A", teamId: team.id, slug: "a" });
      assert.equal(note.status, "open");
      assert.deepEqual(note.tags, []);
      await assert.rejects(typed.ms_notes.insert({ title: "B", teamId: crypto.randomUUID() }), isCode("IL4011"));
      await matchesModels(typed, second.snapshot);
      const recorded = await db.$sql(`SELECT "name", length("checksum") AS n FROM "inferlo_migrations" ORDER BY "name"`);
      assert.deepEqual(recorded.map((r) => ({ ...r })), [{ name: "0001_init", n: 64 }, { name: "0002_more", n: 64 }]);

      const { slug, title, ownerId: _owner, ...rest } = NoteV2.fields;
      const Memo = model("ms_memos", { ...rest, headline: title, handle: slug });
      const third = planMigration([Team, Memo], second.snapshot, { dialect: "sqlite", allowDrop: true, renames: { ms_notes: "ms_memos", "ms_notes.title": "ms_memos.headline", "ms_notes.slug": "ms_memos.handle" } });
      assert.deepEqual(await applyMigrations(db, [...migrations, { name: "0003_memos", sql: file(third.statements) }]), ["0003_memos"]);
      const memos = createDb([Team, Memo], db.$adapter);
      await matchesModels(memos, third.snapshot);
      const kept = await memos.ms_memos.findOne({ id: note.id });
      assert.equal(kept?.headline, "A", "the renamed column kept its data");
      assert.equal(kept?.handle, "a");
      await assert.rejects(memos.ms_memos.insert({ headline: "C", teamId: team.id, status: "nope" as "open" }));
      await memos.ms_teams.delete(team.id);
      assert.equal(await memos.ms_memos.count(), 0, "ON DELETE CASCADE still points at the team table");

      let edited: string[] = [];
      await applyMigrations(db, [{ name: "0001_init", sql: "SELECT 1" }], { onEdited: (names) => (edited = names) });
      assert.deepEqual(edited, ["0001_init"]);
    } finally {
      await db.$close();
    }
  });

  test("table rebuilds keep the data and the references to the table; rows that do not fit roll the file back", async () => {
    const db = createDb([], sqlite({ path: path.join(tempDir(), "app.db") }));
    try {
      const Owner = model("mr_owners", { name: t.string().max(40) });
      const Pet = model("mr_pets", { ownerId: t.ref("mr_owners", { onDelete: "cascade" }), kind: t.enum(["cat", "dog"]).default("cat"), age: t.int().optional(), nick: t.string().optional().unique() });
      const v1 = planMigration([Owner, Pet], undefined, { dialect: "sqlite" });
      await applyMigrations(db, [{ name: "0001_init", sql: file(v1.statements) }]);
      const typed1 = createDb([Owner, Pet], db.$adapter);
      const ann = await typed1.mr_owners.insert({ name: "Ann" });
      const rex = await typed1.mr_pets.insert({ ownerId: ann.id, kind: "dog", age: 3, nick: "rex" });
      await typed1.mr_pets.insert({ ownerId: ann.id });

      // The referenced table is rebuilt too: mr_pets keeps pointing at it.
      const OwnerV2 = model("mr_owners", { name: t.string().max(40), active: t.boolean().optional() });
      const OwnerV3 = model("mr_owners", { name: t.string().max(40).optional(), active: t.boolean().default(true) });
      const PetV2 = model("mr_pets", { ownerId: t.ref("mr_owners", { onDelete: "restrict" }), kind: t.enum(["cat", "dog", "bird"]).default("bird"), age: t.number().default(1), nick: t.string().optional().unique() });
      const v2 = planMigration([OwnerV2, Pet], v1.snapshot, { dialect: "sqlite" });
      const v3 = planMigration([OwnerV3, PetV2], v2.snapshot, { dialect: "sqlite", allowChange: true });
      assert.deepEqual(await applyMigrations(db, [{ name: "0001_init", sql: file(v1.statements) }, { name: "0002_active", sql: file(v2.statements) }, { name: "0003_rebuild", sql: file(v3.statements) }]), ["0002_active", "0003_rebuild"]);
      const typed = createDb([OwnerV3, PetV2], db.$adapter);
      await matchesModels(typed, v3.snapshot);
      const pets = await typed.mr_pets.findMany({ orderBy: { createdAt: "asc" } });
      assert.deepEqual(pets.map((p) => [p.kind, p.age, p.nick ?? null]), [["dog", 3, "rex"], ["cat", 1, null]]);
      assert.equal((await typed.mr_owners.find(ann.id))?.active, true, "NULL got the new default");
      await assert.rejects(typed.mr_pets.insert({ ownerId: ann.id, nick: "rex" }), isCode("IL4004"), "the unique index was created again");
      await assert.rejects(typed.mr_pets.insert({ ownerId: crypto.randomUUID() }), isCode("IL4011"), "foreign keys are enforced again");
      await assert.rejects(typed.mr_owners.delete(ann.id), isCode("IL4011"), "ON DELETE RESTRICT now applies");
      assert.equal((await typed.mr_pets.find(rex.id))?.kind, "dog");

      // A removed enum value still in use fails the rebuild, and the file is rolled back.
      const PetV3 = model("mr_pets", { ...PetV2.fields, kind: t.enum(["cat", "bird"]).default("bird") });
      const bad = planMigration([OwnerV3, PetV3], v3.snapshot, { dialect: "sqlite", allowChange: true });
      await assert.rejects(applyMigrations(db, [{ name: "0004_bad", sql: file(bad.statements) }]), (e: unknown) => isCode("IL4039")(e) && /CHECK constraint failed/.test((e as Error).message));
      assert.equal(await typed.mr_pets.count(), 2, "the old table is still there");
      // A reference pointed at another table whose ids the rows do not have fails the foreign key check.
      const Vet = model("mr_vets", { name: t.string().max(40) });
      const PetV4 = model("mr_pets", { ...PetV2.fields, ownerId: t.ref("mr_vets") });
      const moved = planMigration([OwnerV3, Vet, PetV4], v3.snapshot, { dialect: "sqlite", allowChange: true });
      await assert.rejects(applyMigrations(db, [{ name: "0004_vets", sql: file(moved.statements) }]), (e: unknown) => isCode("IL4039")(e) && /pointing at rows that do not exist/.test((e as Error).message));
      assert.equal((await db.$sql(`SELECT count(*) AS n FROM sqlite_master WHERE name = 'mr_vets'`))[0]!.n, 0);
      assert.equal(Number((await db.$sql("PRAGMA foreign_keys"))[0]!.foreign_keys), 1, "foreign keys are on again after a failure");
    } finally {
      await db.$close();
    }
  });

  test("a failing statement is IL4039 naming it, and the whole file is rolled back", async () => {
    const db = createDb([], sqlite({ path: path.join(tempDir(), "app.db") }));
    try {
      const sql = `CREATE TABLE "ms_partial" ("id" INTEGER PRIMARY KEY);\nINSERT INTO "ms_missing" VALUES (1);\nCREATE TABLE "ms_never" ("id" INTEGER)`;
      await assert.rejects(applyMigrations(db, [{ name: "0001_partial", sql }]), (e: unknown) => {
        assert.ok(isCode("IL4039")(e));
        assert.match((e as Error).message, /0001_partial failed at statement 2 of 3/);
        assert.deepEqual((e as InferloError).details, { migration: "0001_partial", statement: 2, sql: 'INSERT INTO "ms_missing" VALUES (1)' });
        return true;
      });
      assert.equal((await db.$sql(`SELECT count(*) AS n FROM sqlite_master WHERE name IN ('ms_partial', 'ms_never')`))[0]!.n, 0, "nothing was applied");
      assert.equal((await db.$sql(`SELECT count(*) AS n FROM "inferlo_migrations"`))[0]!.n, 0);
      assert.deepEqual(await applyMigrations(db, [{ name: "0001_partial", sql: `CREATE TABLE "ms_partial" ("id" INTEGER PRIMARY KEY); -- it's fine\nSELECT 'a\\'; SELECT 'b'` }]), ["0001_partial"], "a backslash does not escape a quote in SQLite");
    } finally {
      await db.$close();
    }
  });
});

describe("inferlo db migrate (CLI, sqlite)", () => {
  test("writes SQLite migration files and applies them", () => {
    const dir = tempDir();
    mkdirSync(path.join(dir, "src"));
    writeFileSync(path.join(dir, "package.json"), JSON.stringify({ type: "module" }));
    const writeApp = (models: string) => {
      const index = JSON.stringify(path.join(repo, "src", "index.ts"));
      const lite = JSON.stringify(path.join(repo, "src", "db", "sqlite.ts"));
      writeFileSync(
        path.join(dir, "src", "app.ts"),
        `import { createApp, model, t } from ${index};\nimport { sqlite } from ${lite};\n${models}\nexport const app = createApp({ models, routes: [], db: sqlite({ path: ${JSON.stringify(path.join(dir, "app.db"))} }), logger: { info() {}, error() {} } });\n`,
      );
    };
    const cli = (...args: string[]) => spawnSync("node", [path.join(repo, "src", "cli", "main.ts"), ...args, "--json"], { cwd: dir, encoding: "utf8" });
    writeApp('const models = [model("cli_notes", { title: t.string().max(80) })];');
    const r1 = cli("db", "migrate", "init");
    assert.equal(r1.status, 0, r1.stderr);
    assert.match(readFileSync(path.join(dir, "migrations", "0001_init.sql"), "utf8"), /CREATE TABLE IF NOT EXISTS "cli_notes"/);
    assert.equal(JSON.parse(readFileSync(path.join(dir, "migrations", "snapshot.json"), "utf8")).dialect, "sqlite");
    writeApp('const models = [model("cli_notes", { heading: t.string().max(80), done: t.boolean().default(false) })];');
    const r2 = cli("db", "migrate", "heading", "--rename", "cli_notes.title=cli_notes.heading");
    assert.equal(r2.status, 0, r2.stderr);
    assert.deepEqual(JSON.parse(r2.stdout).statements, ['ALTER TABLE "cli_notes" RENAME COLUMN "title" TO "heading"', `ALTER TABLE "cli_notes" ADD COLUMN "done" INTEGER DEFAULT 0 NOT NULL`]);
    const r3 = cli("db", "migrate", "--apply");
    assert.equal(r3.status, 0, r3.stderr);
    assert.deepEqual(JSON.parse(r3.stdout), { ok: true, applied: ["0001_init", "0002_heading"], edited: [] });
  });
});
